import { readFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const [configArgument, typesArgument] = process.argv.slice(2)

if (!configArgument || !typesArgument) {
  throw new Error('Usage: node check-wrangler-bindings.mjs <wrangler.jsonc> <types.d.ts>')
}

const configPath = resolve(process.cwd(), configArgument)
const typesPath = resolve(process.cwd(), typesArgument)
const config = JSON.parse(await readFile(configPath, 'utf8'))
const types = await readFile(typesPath, 'utf8')
const bindings = new Set(Object.keys(config.vars ?? {}))

function collectBindings(value) {
  if (Array.isArray(value)) {
    for (const item of value) collectBindings(item)
    return
  }
  if (!value || typeof value !== 'object') return
  if (typeof value.binding === 'string') bindings.add(value.binding)
  for (const child of Object.values(value)) collectBindings(child)
}

collectBindings(config)
for (const rateLimit of config.ratelimits ?? []) {
  if (typeof rateLimit.name === 'string') bindings.add(rateLimit.name)
}

const missing = [...bindings].filter((binding) =>
  !new RegExp(`\\b${binding.replace(/[.*+?^${}()|[\\]\\]/g, '\\$&')}\\??:`).test(types),
)

if (missing.length) {
  throw new Error(`Generated Cloudflare types are missing bindings: ${missing.join(', ')}`)
}

if (!types.includes('Generated by Wrangler')) {
  throw new Error('Cloudflare types were not generated by Wrangler')
}

console.log(`Cloudflare types cover ${bindings.size} bindings from ${configArgument}`)
